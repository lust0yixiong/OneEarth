export type AgUiAdmission={threadId:string;turnId:string;fingerprint:string;resume?:AgUiResume;workspaceTool?:boolean;workspaceReplies?:AgUiWorkspaceReply[];pendingWorkspaceToolCallIds?:string[];previousTaskId?:string};
export const agUiSchema=`
 CREATE TABLE IF NOT EXISTS runtime_agui_runs (
  id uuid PRIMARY KEY REFERENCES runtime_chat_messages(id),thread_id uuid NOT NULL,turn_id uuid NOT NULL,
  fingerprint text NOT NULL,message_open boolean NOT NULL DEFAULT false,public_text text NOT NULL DEFAULT '',terminal boolean NOT NULL DEFAULT false
 );
 CREATE TABLE IF NOT EXISTS runtime_agui_events (
  seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id uuid NOT NULL REFERENCES runtime_agui_runs(id),event jsonb NOT NULL
 );
 CREATE INDEX IF NOT EXISTS runtime_agui_events_run ON runtime_agui_events(run_id,seq);
 ALTER TABLE runtime_agui_runs ADD COLUMN IF NOT EXISTS public_step text;
` + agUiInterruptSchema + agUiWorkspaceSchema;
export async function writeAgUiEvent(db:PoolClient,id:string,value:unknown){
 const event=EventSchema.parse(value);
 await db.query("INSERT INTO runtime_agui_events(run_id,event) VALUES($1,$2)",[id,event]);
}
/** Only original persisted lifecycle facts select these public names. Free
 * stage text, tool receipts and model output never become progress events. */
export function agUiProgressStep(payload:Payload):NativeAgUiStep|undefined{
 if(payload.remoteStop!==undefined)return;
 const phase=payload.runtimePhase;
 if(phase&&typeof phase==="object"&&!Array.isArray(phase)){
  const {phase:name,operation}=phase as {phase?:unknown;operation?:unknown};
  if(name==="queued")return "research-queued";
  if(name==="executing")return "research-executing";
  if(name==="resuming")return "research-resuming";
  if(name==="waiting-discovery")return operation==="read"?"source-read-wait":operation===undefined||operation==="discover"?"discovery-wait":undefined;
  return;
 }
 if(phase===undefined&&payload.chatPhase==="foreground")return "foreground";
}
export async function projectAgUiProgress(db:PoolClient,id:string,payload:Payload){
 const step=agUiProgressStep(payload);if(!step)return;
 const {rows:[run]}=await db.query<{public_step:string|null}>("SELECT public_step FROM runtime_agui_runs WHERE id=$1 AND NOT terminal FOR UPDATE",[id]);
 if(!run||run.public_step===step)return;
 if(run.public_step&&nativeAgUiStepLabel(run.public_step))await writeAgUiEvent(db,id,{type:"STEP_FINISHED",stepName:run.public_step});
 await writeAgUiEvent(db,id,{type:"STEP_STARTED",stepName:step});
 await db.query("UPDATE runtime_agui_runs SET public_step=$2 WHERE id=$1",[id,step]);
}
/** An explicitly public, completed provider summary is a display object,
 * never model history. Unknown/private markers and raw thinking stay archived. */
export function completeAgUiSummary(taskId:string,value:unknown):ProviderReasoningSnapshot|undefined{
 if(!value||typeof value!=="object"||Array.isArray(value))return;
 const s=value as Record<string,unknown>;
 if(Object.keys(s).some(key=>!["id","revision","kind","text","complete","truncated"].includes(key))||
  typeof s.id!=="string"||!s.id.startsWith(taskId+":")||s.id.length>160||
  typeof s.revision!=="number"||!Number.isSafeInteger(s.revision)||s.revision<1||s.revision>providerReasoningLimits.revisions||
  s.kind!=="summary"||s.complete!==true||s.truncated!==undefined&&s.truncated!==false||typeof s.text!=="string"||!s.text.trim()||Buffer.byteLength(s.text)>providerReasoningLimits.textBytes)return;
 let filtered:ProviderReasoningSnapshot|undefined;
 const archive=providerReasoningArchive(taskId,[],snapshot=>{filtered=snapshot;});
 archive.accept(s as ProviderReasoningSnapshot);
 if(!filtered||filtered.kind!=="summary"||filtered.complete!==true||filtered.truncated||!filtered.text.trim()||Buffer.byteLength(filtered.text)>providerReasoningLimits.textBytes)return;
 return filtered;
}
/** Called after the original raw event INSERT, in that same transaction.
 * The original run lock serializes dedupe, caps and the complete five frames. */
export async function projectAgUiSummary(db:PoolClient,id:string,payload:Payload,sourceSeq:string){
 if(payload.remoteStop!==undefined||payload.cancellationReceipt!==undefined)return;
 const summary=completeAgUiSummary(id,payload.providerReasoning);if(!summary)return;
 if(!(await db.query("SELECT id FROM runtime_agui_runs WHERE id=$1 AND NOT terminal FOR UPDATE",[id])).rowCount)return;
 const messageId=nativeAgUiSummaryPrefix(id)+createHash("sha256").update(summary.id).digest("hex").slice(0,24);
 if((await db.query("SELECT 1 FROM runtime_agui_events WHERE run_id=$1 AND event->>'type'='REASONING_START' AND event->>'messageId'=$2 LIMIT 1",[id,messageId])).rowCount)return;
 // Read only revision/type flags from earlier original rows. Partial or stale
 // revisions cannot be promoted by replaying an independently shaped value.
 const {rows:prior}=await db.query<{revision:unknown;kind:string|null;complete:unknown;truncated:unknown}>(`SELECT snapshot->'revision' AS revision,snapshot->>'kind' AS kind,snapshot->'complete' AS complete,snapshot->'truncated' AS truncated FROM (
   SELECT seq,payload->'providerReasoning' AS snapshot FROM runtime_chat_events WHERE id=$1 AND seq<$3 AND payload->'providerReasoning'->>'id'=$2
   UNION ALL
   SELECT seq,payload->'providerReasoning' AS snapshot FROM runtime_events WHERE id=$1 AND seq<$3 AND payload->'providerReasoning'->>'id'=$2
  ) previous ORDER BY seq DESC LIMIT 25`,[id,summary.id,sourceSeq]);
 if(prior.length>providerReasoningLimits.revisions)return;
 let accepted:{revision:number;kind:string;complete:boolean;truncated:boolean}|undefined;
 for(const old of [...prior].reverse()){
  if(typeof old.revision!=="number"||!Number.isInteger(old.revision)||old.revision<1||old.revision>providerReasoningLimits.revisions||!old.kind||!["summary","deepseek-thinking"].includes(old.kind))continue;
  if(accepted&&(old.revision<=accepted.revision||accepted.complete||old.kind!==accepted.kind))continue;
  const truncated=old.truncated===true||!!accepted?.truncated;
  accepted={revision:old.revision,kind:old.kind,complete:old.complete===true&&!truncated,truncated};
 }
 if(accepted&&(accepted.revision>=summary.revision||accepted.kind!=="summary"||accepted.complete||accepted.truncated))return;
 const {rows:[used]}=await db.query<{count:number;bytes:number}>(`SELECT count(*)::int AS count,coalesce(sum(octet_length(event->>'delta')),0)::int AS bytes
   FROM runtime_agui_events WHERE run_id=$1 AND event->>'type'='REASONING_MESSAGE_CONTENT'`,[id]);
 if(used.count>=providerReasoningLimits.snapshots||used.bytes+Buffer.byteLength(summary.text)>providerReasoningLimits.totalBytes)return;
 for(const event of [
  {type:"REASONING_START",messageId},
  {type:"REASONING_MESSAGE_START",messageId,role:"reasoning"},
  {type:"REASONING_MESSAGE_CONTENT",messageId,delta:summary.text},
  {type:"REASONING_MESSAGE_END",messageId},
  {type:"REASONING_END",messageId},
 ])await writeAgUiEvent(db,id,event);
}
export async function admitAgUi(db:PoolClient,id:string,input:AgUiAdmission){
 await claimAgUiResume(db,id,input.threadId,input.resume);
 await bindAgUiWorkspaceReplies(db,input.threadId,input.previousTaskId,input.workspaceReplies??[],id,input.pendingWorkspaceToolCallIds);
 await db.query("INSERT INTO runtime_agui_runs(id,thread_id,turn_id,fingerprint,workspace_tool) VALUES($1,$2,$3,$4,$5)",[id,input.threadId,input.turnId,input.fingerprint,!!input.workspaceTool]);
 await writeAgUiEvent(db,id,{type:"RUN_STARTED",threadId:input.threadId,runId:id,protocolVersion:nativeAgUiProtocolVersion});
}
/** This is a new public transport projection. The original research archive,
 * authorized source URLs and execution receipts remain unchanged. */
export function publicAgUiResponse(result:DiscoveryResponse):DiscoveryResponse{
 const {runTrace:_trace,conversationEvidence:_readings,conversationAssertionEvidence:_assertions,...response}=result;
 const projected=modelSafeValue(response);
 if(projected.answerNotes){const {searches:_tools,webSources:_rawSources,paperTrace:_diagnostic,...notes}=projected.answerNotes;projected.answerNotes=notes;}
 assertPublicAnswerSafe(JSON.stringify(projected));return projected;
}
export async function appendAgUiText(db:PoolClient,id:string,delta:string){
 const {rows:[run]}=await db.query<{message_open:boolean}>("SELECT message_open FROM runtime_agui_runs WHERE id=$1 AND NOT terminal FOR UPDATE",[id]);
 if(!run||!delta)return false;
 if(!run.message_open)await writeAgUiEvent(db,id,{type:"TEXT_MESSAGE_START",messageId:id,role:"assistant"});
 await db.query("UPDATE runtime_agui_runs SET message_open=true,public_text=public_text||$2 WHERE id=$1",[id,delta]);
 await writeAgUiEvent(db,id,{type:"TEXT_MESSAGE_CONTENT",messageId:id,delta});return true;
}
/** Called from the original finish/cancel transaction. There is no second
 * task status: this row only records delivery of that same business ending. */
export async function finishAgUi(db:PoolClient,id:string,status:"complete"|"failed"|"cancelled",payload:Payload){
 const {rows:[run]}=await db.query<{thread_id:string;message_open:boolean;public_text:string;workspace_tool:boolean;public_step:string|null}>("SELECT thread_id,message_open,public_text,workspace_tool,public_step FROM runtime_agui_runs WHERE id=$1 AND NOT terminal FOR UPDATE",[id]);
 if(!run)return;
 if(run.public_step&&nativeAgUiStepLabel(run.public_step))await writeAgUiEvent(db,id,{type:"STEP_FINISHED",stepName:run.public_step});
 const result=payload.result as DiscoveryResponse|undefined;
 if(status==="complete"&&result){
  if(run.workspace_tool)await lockAgUiThread(db,run.thread_id);
  const response=publicAgUiResponse(result),message=response.message;
  // An incrementally delivered message is append-only. Never report success
  // for a different repaired/fallback draft under that same message identity.
  if(!message.startsWith(run.public_text))throw Error("公开正文与已保存终稿不一致，未宣布成功。");
  if(!run.message_open)await writeAgUiEvent(db,id,{type:"TEXT_MESSAGE_START",messageId:id,role:"assistant"});
  if(message.length>run.public_text.length)await writeAgUiEvent(db,id,{type:"TEXT_MESSAGE_CONTENT",messageId:id,delta:message.slice(run.public_text.length)});
  await writeAgUiEvent(db,id,{type:"TEXT_MESSAGE_END",messageId:id});
  const prompt=response.clarificationPrompt,check=response.questionCheck;
  let interrupt;
  if(check!==undefined){
   if(!validAgUiQuestionCheck(check)||validClarificationPrompt(prompt))throw Error("问题确认缺少唯一有效的原记录。");
   response.questionCheck={originalQuestion:check.originalQuestion,proposedQuestion:check.proposedQuestion};
   await saveAgUiQuestionCheck(db,id,run.thread_id,response.questionCheck);
   interrupt=agUiQuestionCheckDefinition(id,response.message);
  }else if(validClarificationPrompt(prompt)){
   await saveAgUiInterrupt(db,id,run.thread_id,prompt);
   interrupt=agUiInterruptDefinition(id,prompt);
  }
  const call=run.workspace_tool&&!interrupt?workspaceToolCall(id,response):undefined;
  if(run.workspace_tool&&response.workspaceEffect&&!interrupt&&!call)throw Error("工作台原提案无法绑定唯一工具调用。");
  if(call){
   await db.query("UPDATE runtime_agui_runs SET workspace_call=$2 WHERE id=$1",[id,call]);
   await writeAgUiEvent(db,id,{type:"TOOL_CALL_START",toolCallId:call.id,toolCallName:call.function.name,parentMessageId:id});
   await writeAgUiEvent(db,id,{type:"TOOL_CALL_ARGS",toolCallId:call.id,delta:call.function.arguments});
   await writeAgUiEvent(db,id,{type:"TOOL_CALL_END",toolCallId:call.id});
  }
  await writeAgUiEvent(db,id,{type:"RUN_FINISHED",threadId:run.thread_id,runId:id,...(interrupt?{outcome:{type:"interrupt",interrupts:[interrupt]}}:call?{outcome:{type:"success",pendingToolCallIds:[call.id]}}:{}),result:{oneearth:{version:1,messageId:id,response}}});
 }else{
  if(run.message_open)await writeAgUiEvent(db,id,{type:"TEXT_MESSAGE_END",messageId:id});
  await writeAgUiEvent(db,id,status==="cancelled"?{type:"RUN_FINISHED",threadId:run.thread_id,runId:id,outcome:{type:"cancelled"}}:
   {type:"RUN_ERROR",message:"本轮未完成。请查看该运行的已保存记录。",code:typeof payload.code==="string"&&/^[a-z\d_.:-]{1,100}$/iu.test(payload.code)?payload.code:"run_failed"});
 }
 await db.query("UPDATE runtime_agui_runs SET terminal=true,message_open=false,public_step=NULL WHERE id=$1",[id]);
}
