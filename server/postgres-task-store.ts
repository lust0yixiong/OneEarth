import { createHash } from "node:crypto";
import type { PoolClient } from "pg";
import { productDatabase } from "./product-database";
import { TaskConflict,type TaskStore,type Task,type Payload,type TaskStatus } from "./task-store";

export async function postgresTaskStore(namespace:"runtime"|"discovery"):Promise<TaskStore>{
  const pool=productDatabase(namespace==="runtime"?"RUNTIME":"DISCOVERY");
  const tasks=namespace+"_tasks", events=namespace+"_events";
  const lock=namespace==="runtime"?7142501:7142502;
  async function transaction<T>(work:(client:PoolClient)=>Promise<T>):Promise<T>{
    const client=await pool.connect();
    try{
      await client.query("BEGIN");
      const result=await work(client);
      await client.query("COMMIT");
      return result;
    }catch(error){
      await client.query("ROLLBACK").catch(()=>{});
      throw error;
    }finally{client.release();}
  }
  try{
    await transaction(async db=>{
      await db.query("SELECT pg_advisory_xact_lock($1::bigint)",[lock+10]);
      await db.query(`
        CREATE TABLE IF NOT EXISTS ${tasks} (
          id uuid PRIMARY KEY, body text NOT NULL, fingerprint text NOT NULL,
          status text NOT NULL CHECK(status IN ('queued','running','complete','failed','cancelled')),
          created bigint NOT NULL, updated bigint NOT NULL
        );
        CREATE INDEX IF NOT EXISTS ${tasks}_queue ON ${tasks}(status, created);
        CREATE TABLE IF NOT EXISTS ${events} (
          seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          id uuid NOT NULL REFERENCES ${tasks}(id), at bigint NOT NULL, payload jsonb NOT NULL
        );
        CREATE INDEX IF NOT EXISTS ${events}_replay ON ${events}(id,seq);`);
      if(namespace==="runtime"){
        await db.query(`
          CREATE TABLE IF NOT EXISTS runtime_confirmations (
            task_id uuid PRIMARY KEY REFERENCES runtime_tasks(id), parent_task_id uuid,
            decision jsonb, proposal jsonb
          );
          CREATE TABLE IF NOT EXISTS runtime_references (
            task_id uuid NOT NULL REFERENCES runtime_tasks(id), ordinal integer NOT NULL,
            source_channel text, reference jsonb NOT NULL, PRIMARY KEY(task_id,ordinal)
          );`);
      }else{
        await db.query(`
          CREATE TABLE IF NOT EXISTS discovery_findings (
            task_id uuid NOT NULL REFERENCES discovery_tasks(id), seq bigint NOT NULL,
            finding jsonb NOT NULL, PRIMARY KEY(task_id,seq)
          );
          CREATE TABLE IF NOT EXISTS discovery_channels (
            task_id uuid NOT NULL REFERENCES discovery_tasks(id), channel text NOT NULL,
            state jsonb NOT NULL, PRIMARY KEY(task_id,channel)
          );
          CREATE TABLE IF NOT EXISTS discovery_papers (
            id text PRIMARY KEY, task_id uuid NOT NULL REFERENCES discovery_tasks(id), record jsonb NOT NULL
          );`);
      }
    });
  }catch(error){await pool.end();throw error;}
  function row(value:Task):Task{
    return {...value,created:Number(value.created),updated:Number(value.updated)};
  }
  async function write(db:PoolClient,id:string,payload:Payload,at=Date.now()){
    const saved=await db.query(`INSERT INTO ${events}(id,at,payload) VALUES ($1,$2,$3::jsonb) RETURNING seq`,
      [id,at,JSON.stringify(payload)]);
    if(namespace==="discovery"&&payload.finding){
      await db.query("INSERT INTO discovery_findings(task_id,seq,finding) VALUES ($1,$2,$3::jsonb)",
        [id,saved.rows[0].seq,JSON.stringify(payload.finding)]);
    }
  }
  const get=async(id:string)=>{
    const result=await pool.query<Task>(`SELECT * FROM ${tasks} WHERE id=$1`,[id]);
    return result.rows[0] ? row(result.rows[0]) : undefined;
  };
  async function finish(id:string,status:Exclude<TaskStatus,"queued"|"running">,payload:Payload){
    return transaction(async db=>{
      const now=Date.now();
      const updated=await db.query(`UPDATE ${tasks} SET status=$1,updated=$2 WHERE id=$3 AND status IN ('running','queued')`,[status,now,id]);
      if(!updated.rowCount)return false;
      await write(db,id,payload,now);
      const result=payload.result as {
        questionCheck?:unknown;
        answerNotes?:{references?:{sourceChannel?:string}[]};
        sourceStatus?:{source:string}[];
        papers?:{id:string}[];
      }|undefined;
      if(namespace==="runtime"){
        if(result?.questionCheck)await db.query(`INSERT INTO runtime_confirmations(task_id,proposal)
          VALUES ($1,$2::jsonb) ON CONFLICT(task_id) DO UPDATE SET proposal=EXCLUDED.proposal`,[id,JSON.stringify(result.questionCheck)]);
        const references=result?.answerNotes?.references || [];
        for(const [index,reference] of references.entries())
          await db.query("INSERT INTO runtime_references VALUES($1,$2,$3,$4::jsonb)",
            [id,index+1,reference.sourceChannel??null,JSON.stringify(reference)]);
      }else{
        for(const channel of result?.sourceStatus || [])
          await db.query(`INSERT INTO discovery_channels VALUES($1,$2,$3::jsonb)
            ON CONFLICT(task_id,channel) DO UPDATE SET state=EXCLUDED.state`,[id,channel.source,JSON.stringify(channel)]);
        for(const record of result?.papers || [])
          await db.query("INSERT INTO discovery_papers VALUES($1,$2,$3::jsonb) ON CONFLICT(id) DO NOTHING",
            [record.id,id,JSON.stringify(record)]);
      }
      return true;
    });
  }
  let workerConnection:PoolClient|undefined;
  return {
    get,
    ...(namespace==="runtime"?{async materialEvents(id:string){
      const result=await pool.query<{seq:string;at:string;payload:Payload}>(`SELECT seq,at,payload FROM runtime_events
        WHERE id=$1 AND jsonb_typeof(payload->'researchMaterials')='object' ORDER BY seq`,[id]);
      return result.rows.map(({seq,at,payload})=>({...payload,seq:Number(seq),at:Number(at),taskId:id}));
    }}:{}),
    async terminal(id){
      const result=await pool.query<{payload:Payload}>(`SELECT e.payload FROM ${events} e JOIN ${tasks} t ON t.id=e.id
        WHERE e.id=$1 AND t.status NOT IN ('queued','running') ORDER BY e.seq DESC LIMIT 1`,[id]);
      return result.rows[0]?.payload;
    },
    async submit(id,body){
      return transaction(async db=>{
        const raw=JSON.stringify(body), hash=createHash("sha256").update(raw).digest("hex"), now=Date.now();
        const inserted=await db.query<Task>(`INSERT INTO ${tasks}(id,body,fingerprint,status,created,updated)
          VALUES ($1,$2,$3,'queued',$4,$4) ON CONFLICT(id) DO NOTHING RETURNING *`,[id,raw,hash,now]);
        if(!inserted.rowCount){
          const previous=(await db.query<Task>(`SELECT * FROM ${tasks} WHERE id=$1`,[id])).rows[0];
          if(!previous||previous.fingerprint!==hash)throw new TaskConflict("该任务编号已经用于另一份提交。");
          return row(previous);
        }
        const decision=(body as {questionDecision?:{checkMessageId?:string}})?.questionDecision;
        if(namespace==="runtime"&&decision){
          await db.query("INSERT INTO runtime_confirmations(task_id,parent_task_id,decision) VALUES ($1,$2,$3::jsonb)",
            [id,decision.checkMessageId,JSON.stringify(decision)]);
        }
        await write(db,id,{queued:true,queuedAt:now},now);
        return row(inserted.rows[0]);
      });
    },
    async claim(){
      return transaction(async db=>{
        const selected=(await db.query<Task>(`SELECT * FROM ${tasks} WHERE status='queued'
          ORDER BY created,id LIMIT 1 FOR UPDATE SKIP LOCKED`)).rows[0];
        if(!selected)return;
        const now=Date.now();
        await db.query(`UPDATE ${tasks} SET status='running',updated=$1 WHERE id=$2`,[now,selected.id]);
        await write(db,selected.id,{started:true,startedAt:now},now);
        return {id:selected.id,body:JSON.parse(selected.body)};
      });
    },
    async append(id,payload){
      await transaction(async db=>{
        const active=await db.query(`SELECT id FROM ${tasks} WHERE id=$1 AND status='running' FOR UPDATE`,[id]);
        if(active.rowCount)await write(db,id,payload);
      });
    },
    finish,
    async recoverInterrupted(){
      const client=await pool.connect();
      try{
        const elected=await client.query("SELECT pg_try_advisory_lock($1::bigint) AS acquired",[lock]);
        if(!elected.rows[0].acquired)throw Error("同一任务库已有后台 worker。");
        const interrupted=await pool.query<{id:string}>(`SELECT id FROM ${tasks} WHERE status='running'`);
        for(const {id} of interrupted.rows)await finish(id,"failed",{
          error:"后台进程中断。已取得的结果仍可查看，请明确重试未完成的工作。",code:"worker_interrupted"});
        client.on("error",()=>{
          console.error("OneEarth "+namespace+" worker lost its PostgreSQL lease");
          process.exit(1);
        });
        workerConnection=client;
      }catch(error){client.release(true);throw error;}
    },
    async events(id,after){
      const result=await pool.query<{seq:string;at:string;payload:Payload}>(`SELECT seq,at,payload FROM ${events}
        WHERE id=$1 AND seq>$2 ORDER BY seq LIMIT 128`,[id,after]);
      return result.rows.map(({seq,at,payload})=>({...payload,seq:Number(seq),at:Number(at),taskId:id}));
    },
    async close(){workerConnection?.release(true);await pool.end();},
  };
}
